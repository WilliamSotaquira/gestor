<p>La planeación participativa es entendida como el mecanismo mediante el cual la ciudadanía decide le rumbo de políticas, planes, programas, proyectos o trámites de acuerdo con sus necesidades. La participación puede darse en la delimitación de los resultados e impactos esperados y en la definición de productos y de actividades.<br/></p>
<p>El presupuesto participativo es el proceso por medio del cual la ciudadanía, a través de la deliberación y la construcción de acuerdos con el Gobierno, asignan un porcentaje de los recursos del presupuesto a programas y proyectos que consideran prioritarios en armonía con el Plan de Desarrollo.<br/></p>
<p>Según lo dispuesto en los artículos 90, 91, 92 y 93 de la Ley 1757 de 2015, son las entidades territoriales las obligadas a realizar ejercicios de presupuesto participativo, cuyos resultados son presentados ante los Consejos Regionales, Municipales y Locales de Planeación, según sea el caso, para su inclusión en el presupuesto institucional; 
   <strong>por lo cual este ejercicio no aplica para el Ministerio de las Culturas las Artes y los Saberes.</strong></p>
