<h2>Modalidades de control social​<br/></h2>
<p>El control social es el derecho ciudadano de hacer seguimiento y evaluar el resultado de políticas públicas y/o incidir en decisiones de planificación y ejecución de acciones institucionales, por lo que las entidades de la administración pública debemos de facilitar el ejercicio del control no solo en cumplimiento de la ley 489 de 1998, Capítulo VII “Democratización y control social de la administración pública y si no con el objeto&#160; fundamental de fortalecer la interacción del Ministerio con las personas, usuarios y grupos de interés y por esto promovernos el control social a través de encuentros, audiencias, consultas y seguimiento a veedurías ciudadanas.&#160;​​<br/></p>
<p>La guía ABC de la Ley 1757 de 2015 ESTATUTO DE LA PARTICIPACIÓN DEMOCRÁTICA EN COLOMBIA, del Departamento Administrativo de la Función Pública, menciona los instrumentos con los que las personas o colectivos pueden ejercer su derecho al control social, ya sea para solicitar la información, entregar observaciones o requerir respuestas específicas a las situaciones denunciada:&#160;&#160;<br/></p>
<ul>
   <li>
      <p>Solicitar la información pública que se requiera para el desarrollo de su labor, en los términos del Código de Procedimiento Administrativo y de lo Contencioso Administrativo.</p>
   </li>
   <li>
      <p>Presentar observaciones de la labor desarrollada al ente encargado de la política pública;</p>
   </li>
   <li>
      <p>Presentar peticiones, denuncias, quejas y reclamos ante las autoridades competentes.</p>
   </li>
   <li>
      <p>Presentar acciones populares en los términos de la Ley 472 de 1998;</p>
   </li>
   <li>
      <p>Presentar acciones de cumplimiento en los términos de la Ley 393 de 1997;</p>
   </li>
   <li>
      <p>Presentar Acciones de Tutela en los términos del Decreto número 2591 de 1991;</p>
   </li>
   <li>
      <p>Participar en Audiencias Públicas ante los entes que las convoquen;</p>
   </li>
   <li>
      <p>Hacer uso de los recursos y acciones legales que se requieran para el desarrollo del control social​</p>
   </li>
</ul>

